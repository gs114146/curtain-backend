@push('scripts')
    <script>
        $(document).ready(function() {
            let currentPage = 1;
            let totalPages = 1;
            let searchTerm = '';

            // Load data on page load
            loadData();

            // Search functionality
            $('#searchInput').on('input', function() {
                searchTerm = $(this).val();
                currentPage = 1;
                loadData();
            });

            // Load data function
            function loadData() {
                $.ajax({
                    url: '@yield('data-url')',
                    method: 'GET',
                    data: {
                        page: currentPage,
                        search: searchTerm
                    },
                    success: function(response) {
                        updateTable(response.data);
                        updatePagination(response);
                    },
                    error: function(xhr) {
                        showToast('Error loading data', 'error');
                    }
                });
            }

            // Update table content
            function updateTable(data) {
                let html = '';
                if (data.length === 0) {
                    html = '<tr><td colspan="100%" class="text-center py-4">No data found</td></tr>';
                } else {
                    data.forEach(function(item) {
                        html += generateTableRow(item);
                    });
                }
                $('#dataTableBody').html(html);
            }

            // Generate table row - to be overridden by each view
            function generateTableRow(item) {
                return @yield('table-row-template');
            }

            // Update pagination
            function updatePagination(response) {
                totalPages = response.last_page;
                currentPage = response.current_page;

                let paginationHtml = '';

                // Previous button
                if (currentPage > 1) {
                    paginationHtml +=
                        `<li class="page-item"><a class="page-link" href="#" data-page="${currentPage - 1}">Previous</a></li>`;
                }

                // Page numbers
                for (let i = Math.max(1, currentPage - 2); i <= Math.min(totalPages, currentPage + 2); i++) {
                    paginationHtml += `<li class="page-item ${i === currentPage ? 'active' : ''}">
                <a class="page-link" href="#" data-page="${i}">${i}</a>
            </li>`;
                }

                // Next button
                if (currentPage < totalPages) {
                    paginationHtml +=
                        `<li class="page-item"><a class="page-link" href="#" data-page="${currentPage + 1}">Next</a></li>`;
                }

                $('#pagination').html(paginationHtml);

                // Update showing info
                const start = (currentPage - 1) * response.per_page + 1;
                const end = Math.min(currentPage * response.per_page, response.total);
                $('#showingStart').text(start);
                $('#showingEnd').text(end);
                $('#totalRecords').text(response.total);
            }

            // Pagination click handler
            $(document).on('click', '.page-link', function(e) {
                e.preventDefault();
                currentPage = parseInt($(this).data('page'));
                loadData();
            });

            // Create form submission
            $('#createForm').on('submit', function(e) {
                e.preventDefault();
                const formData = new FormData(this);
                const submitBtn = $(this).find('button[type="submit"]');
                const spinner = submitBtn.find('.spinner-border');

                spinner.removeClass('d-none');
                submitBtn.prop('disabled', true);

                $.ajax({
                    url: '@yield('create-url')',
                    method: 'POST',
                    data: formData,
                    processData: false,
                    contentType: false,
                    success: function(response) {
                        $('#createModal').modal('hide');
                        $('#createForm')[0].reset();
                        loadData();
                        showToast('Item created successfully', 'success');
                    },
                    error: function(xhr) {
                        handleFormErrors(xhr, '#createForm');
                    },
                    complete: function() {
                        spinner.addClass('d-none');
                        submitBtn.prop('disabled', false);
                    }
                });
            });

            // Edit form submission
            $('#editForm').on('submit', function(e) {
                e.preventDefault();
                const formData = new FormData(this);
                const submitBtn = $(this).find('button[type="submit"]');
                const spinner = submitBtn.find('.spinner-border');

                spinner.removeClass('d-none');
                submitBtn.prop('disabled', true);

                $.ajax({
                    url: '@yield('edit-url')' + '/' + $('#editId').val(),
                    method: 'POST',
                    data: formData,
                    processData: false,
                    contentType: false,
                    success: function(response) {
                        $('#editModal').modal('hide');
                        loadData();
                        showToast('Item updated successfully', 'success');
                    },
                    error: function(xhr) {
                        handleFormErrors(xhr, '#editForm');
                    },
                    complete: function() {
                        spinner.addClass('d-none');
                        submitBtn.prop('disabled', false);
                    }
                });
            });

            // Delete functionality
            let deleteId = null;

            $(document).on('click', '.btn-delete', function() {
                deleteId = $(this).data('id');
                $('#deleteModal').modal('show');
            });

            $('#confirmDelete').on('click', function() {
                const submitBtn = $(this);
                const spinner = submitBtn.find('.spinner-border');

                spinner.removeClass('d-none');
                submitBtn.prop('disabled', true);

                $.ajax({
                    url: '@yield('delete-url')' + '/' + deleteId,
                    method: 'DELETE',
                    data: {
                        _token: $('meta[name="csrf-token"]').attr('content')
                    },
                    success: function(response) {
                        $('#deleteModal').modal('hide');
                        loadData();
                        showToast('Item deleted successfully', 'success');
                    },
                    error: function(xhr) {
                        showToast('Error deleting item', 'error');
                    },
                    complete: function() {
                        spinner.addClass('d-none');
                        submitBtn.prop('disabled', false);
                    }
                });
            });

            // Edit button click handler
            $(document).on('click', '.btn-edit', function() {
                const id = $(this).data('id');

                $.ajax({
                    url: '@yield('show-url')' + '/' + id,
                    method: 'GET',
                    success: function(response) {
                        populateEditForm(response);
                        $('#editModal').modal('show');
                    },
                    error: function(xhr) {
                        showToast('Error loading item data', 'error');
                    }
                });
            });

            // Populate edit form - to be overridden by each view
            function populateEditForm(data) {
                @yield('populate-edit-form');
            }

            // Handle form errors
            function handleFormErrors(xhr, formSelector) {
                if (xhr.status === 422) {
                    const errors = xhr.responseJSON.errors;
                    $(formSelector + ' .is-invalid').removeClass('is-invalid');
                    $(formSelector + ' .invalid-feedback').remove();

                    Object.keys(errors).forEach(function(field) {
                        const input = $(formSelector + ' [name="' + field + '"]');
                        input.addClass('is-invalid');
                        input.after('<div class="invalid-feedback">' + errors[field][0] + '</div>');
                    });
                } else {
                    showToast('An error occurred', 'error');
                }
            }

            // Show toast notification
            function showToast(message, type = 'info') {
                // Implementation depends on your toast system
                console.log(type + ': ' + message);
            }
        });
    </script>
@endpush
